def extract_embeddings(video_path, model, chunk_duration=0.1):
    # 1. Load audio (16kHz)
    y, sr = librosa.load(video_path, sr=16000)

    # 2. Define chunk size
    chunk_samples = int(chunk_duration * sr) # 1600 samples for 100ms

    embeddings = []

    # 3. Process in 100ms chunks
    for i in range(0, len(y), chunk_samples):
        chunk = y[i : i + chunk_samples]
        if len(chunk) < chunk_samples:
            continue

        # Convert to tensor
        inputs = torch.tensor(chunk).to(device).float()

        # Reshape for Conv2d: EAT expects [Batch, Channels, Height, Width]
        # For 1600 samples, we reshape to [1, 1, 16, 100] (standard for EAT-base chunks)
        inputs = inputs.view(1, 1, 16, 100)

        with torch.no_grad():
            outputs = model(inputs)
            # Extract the representation.
            # Custom models often return different structures; we'll access hidden_states or the direct output
            if hasattr(outputs, 'last_hidden_state'):
                embedding = outputs.last_hidden_state.mean(dim=1)
            else:
                # Fallback for EATModel return type
                embedding = outputs.mean(dim=1) if len(outputs.shape) > 1 else outputs

            embeddings.append(embedding.squeeze().cpu().numpy())

    return np.array(embeddings)

