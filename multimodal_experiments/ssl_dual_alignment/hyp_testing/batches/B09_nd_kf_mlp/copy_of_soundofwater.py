"""### Layer 7 Feature Extraction & Visualization
We will now specifically target the internal representations at **Layer 7** to see how the acoustic space differs from the final output layer.
"""

import torch
import numpy as np
import librosa
from tqdm.auto import tqdm

def extract_layer_embeddings_v3(video_path, model, layer_idx=7, chunk_duration=0.1):
    # Load audio
    y, sr = librosa.load(video_path, sr=16000)
    chunk_samples = int(chunk_duration * sr)
    embeddings = []
    core = model.model

    num_chunks = len(y) // chunk_samples
    pbar = tqdm(total=num_chunks, desc=f"Processing {video_path.split('/')[-1]}")

    for i in range(0, len(y), chunk_samples):
        chunk = y[i : i + chunk_samples]
        if len(chunk) < chunk_samples: continue

        inputs = torch.tensor(chunk).to(device).float().view(1, 1, 16, 100)

        with torch.no_grad():
            # 1. Patch Embedding
            out = core.local_encoder(inputs)
            x = out[0] if isinstance(out, (tuple, list)) else out

            # 2. Add Positional Encoding
            if hasattr(core, 'fixed_positional_encoder'):
                padding_mask = torch.zeros((x.shape[0], x.shape[1]), dtype=torch.bool).to(device)
                pos_out = core.fixed_positional_encoder(x, padding_mask=padding_mask)
                x = pos_out[0] if isinstance(pos_out, (tuple, list)) else pos_out

            # 3. Step through blocks
            for j in range(layer_idx + 1):
                block_out = core.blocks[j](x)
                x = block_out[0] if isinstance(block_out, (tuple, list)) else block_out

            # 4. Pool
            embedding = x.mean(dim=1)
            embeddings.append(embedding.squeeze().cpu().numpy())

        pbar.update(1)
    pbar.close()
    return np.array(embeddings)

