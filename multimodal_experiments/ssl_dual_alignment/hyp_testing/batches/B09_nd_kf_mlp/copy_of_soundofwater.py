preprocess = transforms.Compose([
    transforms.ToPILImage(),
    transforms.Resize((384, 384)),
    transforms.ToTensor(),
    transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]),
])

def extract_visual_embeddings(video_path, model, fps_target=10):
    cap = cv2.VideoCapture(video_path)
    total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    orig_fps = cap.get(cv2.CAP_PROP_FPS)
    if orig_fps == 0: return np.array([])
    frame_interval = max(1, int(orig_fps / fps_target))

    embeddings = []
    filename = os.path.basename(video_path)
    pbar = tqdm(total=total_frames // frame_interval, desc=f"Processing {filename}")

    count = 0
    while cap.isOpened():
        ret, frame = cap.read()
        if not ret: break

        if count % frame_interval == 0:
            img = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
            # V-JEPA expects [B, C, T, H, W]. For a single frame, T=1.
            input_tensor = preprocess(img).unsqueeze(0).unsqueeze(2).to(device)

            with torch.no_grad():
                # The VisionTransformer encoder output
                out = model(input_tensor)

                # If out is a tuple, take the first element (likely the tokens)
                if isinstance(out, (tuple, list)):
                    out = out[0]

                # Handle [B, Tokens, Dim] or [B, C, T, H, W]
                if len(out.shape) == 3:
                    feat = out.mean(dim=1) # Average over tokens
                elif len(out.shape) == 5:
                    feat = out.mean(dim=(2,3,4)) # Spatio-temporal average
                else:
                    feat = out

                embeddings.append(feat.squeeze().cpu().numpy())
            pbar.update(1)
        count += 1

    cap.release()
    pbar.close()
    return np.array(embeddings)

