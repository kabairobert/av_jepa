"""### Cross-Modal Correlation Analysis
To understand the relationship between the sound and the video, we'll calculate the correlation between the EAT (audio) and V-JEPA (visual) embedding trajectories. We'll synchronize the timestamps and correlate the primary directions of change (PC1) for both modalities.
"""

from scipy.stats import pearsonr, spearmanr
from sklearn.decomposition import PCA
import pandas as pd

def calculate_multimodal_correlation(audio_emb, visual_emb):
    # Align lengths by truncation to the shortest sequence
    min_len = min(len(audio_emb), len(visual_emb))
    a_sync = audio_emb[:min_len]
    v_sync = visual_emb[:min_len]

    # Reduce to 1D via first principal component for a simplified correlation measure
    pca_a = PCA(n_components=1).fit_transform(a_sync).flatten()
    pca_v = PCA(n_components=1).fit_transform(v_sync).flatten()

    pearson_corr, _ = pearsonr(pca_a, pca_v)
    spearman_corr, _ = spearmanr(pca_a, pca_v)

    return pearson_corr, spearman_corr

